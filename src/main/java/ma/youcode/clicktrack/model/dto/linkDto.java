package ma.youcode.clicktrack.model.dto;

public class linkDto {
    private String offre;
    private String url;
    public linkDto() {
    }
    public String getOffre() {
        return offre;
    }
    public void setOffre(String offre) {
        this.offre = offre;
    }
    public String getUrl() {
        return url;
    }
    public void setUrl(String url) {
        this.url = url;
    }
}
